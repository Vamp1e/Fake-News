import subprocess, json, hashlib, time, os, re, pathlib

CHAIN = "fakenews"
CFG = "addresses.json"

START_CRED = 100            # starting credibility points for everyone
MIN_SCORE_TO_VALIDATE = 50  # only users with enough credibility may vote
REWARD = 10                 # CRED sent to validators who voted with the verdict
PENALTY = 5                 # points removed (logged on chain) for wrong votes
QUORUM = 3                  # minimum votes before a verdict

STREAMS = ["orgs", "news", "nlp", "votes", "verdicts", "credibility", "fakebacklog"]
ROLES = ["org", "publisher", "validator1", "validator2", "validator3"]

FAKE_WORDS = ["shocking", "you won't believe", "secret", "miracle", "hoax",
              "exposed", "100% proven", "share before", "they don't want"]
REAL_WORDS = ["according to", "officials said", "report", "study",
              "confirmed", "statement", "data", "published"]

def mc(*args):
    # Run: multichain-cli <chain> <args...> and return parsed output
    cmd = ["multichain-cli", CHAIN]
    for a in args:
        if isinstance(a, bool):
            a = "true" if a else "false"
        elif isinstance(a, (dict, list)):
            a = json.dumps(a)
        cmd.append(str(a))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError((r.stderr or r.stdout).strip())
    out = r.stdout.strip()
    try:
        return json.loads(out)
    except ValueError:
        return out

def load_cfg():
    with open(CFG) as f:
        return json.load(f)

def sha256(text):
    return hashlib.sha256(text.encode()).hexdigest()

def stream_items(stream, key):
    try:
        mc("subscribe", stream)
    except RuntimeError:
        pass
    return mc("liststreamkeyitems", stream, key, False, 1000)

def payload(item):
    d = item["data"]
    return d["json"] if isinstance(d, dict) and "json" in d else d

def cred_balance(addr):
    for b in mc("getaddressbalances", addr):
        if b["name"] == "CRED":
            return b["qty"]
    return 0

def credibility_score(addr):
    # score = CRED balance + penalties (negative numbers) logged in the credibility stream
    penalties = sum(payload(it).get("delta", 0) for it in stream_items("credibility", addr))
    return cred_balance(addr) + penalties

def nlp_label(text):
    # simple NLP stand-in: count fake-style and real-style words
    t = text.lower()
    fake = sum(w in t for w in FAKE_WORDS)
    real = sum(w in t for w in REAL_WORDS)
    label = "fake" if fake > real else "real" if real > fake else "suspicious"
    return {"score_fake": fake, "score_real": real, "label": label}

