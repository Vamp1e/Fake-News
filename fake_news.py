def register_org(name):
    cfg = load_cfg()
    mc("publishfrom", cfg["admin"], "orgs", name,
       {"json": {"org": name, "address": cfg["org"], "ts": int(time.time())}})
    print("Organization registered on chain:", name)

def publish(role, news_id, text):
    cfg = load_cfg()
    addr = cfg[role]
    record = {
        "text": text,
        "contentHash": sha256(text),
        "publisherHash": sha256(addr + "salt"),   # validators see a hash, not the ID
        "ts": int(time.time()),
    }
    mc("publishfrom", addr, "news", news_id, {"json": record})
    print("News", news_id, "published by", role)
    res = nlp_label(text)
    mc("publishfrom", cfg["admin"], "nlp", news_id, {"json": res})
    print("NLP result stored:", res)

def vote(role, news_id, choice):
    if choice not in ("real", "fake"):
        raise ValueError("choice must be real or fake")
    cfg = load_cfg()
    addr = cfg[role]
    score = credibility_score(addr)
    if score < MIN_SCORE_TO_VALIDATE:
        raise RuntimeError("Rejected: credibility %s is below %s" % (score, MIN_SCORE_TO_VALIDATE))
    mc("publishfrom", addr, "votes", news_id, {"json": {"vote": choice, "ts": int(time.time())}})
    print(role, "voted", choice, "on", news_id)

def tally(news_id):
    cfg = load_cfg()
    if stream_items("verdicts", news_id):
        raise RuntimeError("Verdict already exists for " + news_id)
    validators = {cfg[v]: v for v in ["validator1", "validator2", "validator3"]}
    votes = {}
    for it in stream_items("votes", news_id):
        voter = it["publishers"][0]
        if voter in validators and voter not in votes:   # one vote per validator
            votes[voter] = payload(it)["vote"]
    print("Votes:", {validators[a]: v for a, v in votes.items()})
    if len(votes) < QUORUM:
        raise RuntimeError("Not enough votes yet (need %d)" % QUORUM)

    n_fake = sum(v == "fake" for v in votes.values())
    n_real = len(votes) - n_fake
    if n_fake == n_real:
        raise RuntimeError("Tie - no verdict")
    verdict = "fake" if n_fake > n_real else "real"

    mc("publishfrom", cfg["admin"], "verdicts", news_id,
       {"json": {"verdict": verdict, "fake": n_fake, "real": n_real, "ts": int(time.time())}})
    print("VERDICT:", verdict.upper())

    if verdict == "fake":
        news = stream_items("news", news_id)
        h = payload(news[0])["contentHash"] if news else ""
        mc("publishfrom", cfg["admin"], "fakebacklog", news_id,
           {"json": {"contentHash": h, "ts": int(time.time())}})
        print("Added to fake-news backlog")

    for addr, v in votes.items():
        if v == verdict:
            mc("sendassetfrom", cfg["admin"], addr, "CRED", REWARD)
            print(validators[addr], "rewarded +%d CRED" % REWARD)
        else:
            mc("publishfrom", cfg["admin"], "credibility", addr,
               {"json": {"delta": -PENALTY, "reason": "wrong vote on " + news_id}})
            print(validators[addr], "penalized -%d" % PENALTY)

